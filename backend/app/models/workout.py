"""
Workout Plan and Workout Log Database Models.

Stores:
1. WorkoutPlan: Prescribed weekly training programs drafted by the deterministic
   engine and Agent 2, reviewed and approved by the trainer.
2. WorkoutLog: In-gym performance records extracted by Agent 1 from client
   voice dictation or natural language chat, including sets, reps, and pain notes.
"""

from datetime import datetime
from typing import Optional
from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.types import JSON

from app.core.database import Base


class WorkoutPlan(Base):
    """
    SQLAlchemy model representing a weekly workout plan.
    
    Status cycle:
      - 'draft': Automatically drafted by progression engine & Agent 2, waiting for trainer review.
      - 'approved': Explicitly signed off by the trainer and visible on the client's phone.
      - 'completed': Past plan archived after a full training cycle.
    """
    __tablename__ = "workout_plans"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    client_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("client_profiles.id", ondelete="CASCADE"), nullable=False, index=True
    )
    
    # Week identifier (e.g., '2026-W45')
    week_label: Mapped[str] = mapped_column(String(50), nullable=False)
    
    # Status: 'draft', 'approved', 'archived'
    status: Mapped[str] = mapped_column(String(50), default="draft", nullable=False, index=True)

    # Structured workout exercises, sets, reps, and target weights
    # Example format:
    # [
    #   {"exercise_id": "ex_bench", "name": "Barbell Bench Press", "sets": 3, "target_reps": 10, "target_weight_lbs": 135},
    #   {"exercise_id": "ex_squat", "name": "Back Squat", "sets": 3, "target_reps": 8, "target_weight_lbs": 185}
    # ]
    exercises_json: Mapped[dict] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), default=list, nullable=False
    )

    # Safety flags and explanations generated by Agent 2 during review
    # Example format:
    # [
    #   {"severity": "warning", "message": "Shoulder pain reported last week. Exercise held at 135 lbs."}
    # ]
    safety_flags_json: Mapped[dict] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), default=list, nullable=False
    )

    trainer_notes: Mapped[str] = mapped_column(Text, nullable=True)
    approved_at: Mapped[datetime] = mapped_column(DateTime, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=datetime.utcnow, onupdate=datetime.utcnow
    )

    # Relationships
    client: Mapped["ClientProfile"] = relationship("ClientProfile", back_populates="workout_plans")  # noqa: F821
    logs: Mapped[list["WorkoutLog"]] = relationship("WorkoutLog", back_populates="plan")


class WorkoutLog(Base):
    """
    SQLAlchemy model representing a workout session completed and logged by a client.
    
    Contains both the raw voice/text input provided by the client and the structured
    set rows parsed by Agent 1.
    """
    __tablename__ = "workout_logs"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    client_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("client_profiles.id", ondelete="CASCADE"), nullable=False, index=True
    )
    plan_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("workout_plans.id", ondelete="SET NULL"), nullable=True, index=True
    )

    # Client-generated UUID for idempotency protection (prevents duplicate submissions on retry)
    client_request_id: Mapped[Optional[str]] = mapped_column(
        String(64), unique=True, nullable=True, index=True
    )

    # Raw voice transcript or chat message entered by the client
    raw_input: Mapped[str] = mapped_column(Text, nullable=False)

    # Structured set extractions produced by Agent 1
    # Example format:
    # [
    #   {"exercise_id": "ex_bench", "set_num": 1, "reps": 10, "weight_lbs": 135.0, "pain_flag": false},
    #   {"exercise_id": "ex_bench", "set_num": 2, "reps": 10, "weight_lbs": 135.0, "pain_flag": false},
    #   {"exercise_id": "ex_bench", "set_num": 3, "reps": 8, "weight_lbs": 135.0, "pain_flag": true, "note": "shoulder pinching"}
    # ]
    extracted_sets_json: Mapped[dict] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), default=list, nullable=False
    )

    # Overall pain or injury flags detected in this workout
    has_pain_flag: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    pain_summary: Mapped[str] = mapped_column(Text, nullable=True)

    logged_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)

    # Relationships
    client: Mapped["ClientProfile"] = relationship("ClientProfile", back_populates="workout_logs")  # noqa: F821
    plan: Mapped["WorkoutPlan"] = relationship("WorkoutPlan", back_populates="logs")
