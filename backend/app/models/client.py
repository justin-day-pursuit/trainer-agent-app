"""
Client Profile and Session Link Database Models.

Defines the structure for storing:
1. ClientProfile: Physical goals, injury notes, and intake history.
2. ClientSession: Unique, non-guessable session tokens (UUIDs) that allow
   clients to log workouts and view progress without needing account passwords.
"""

from datetime import datetime
import uuid
from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.types import JSON

from app.core.database import Base


class ClientProfile(Base):
    """
    SQLAlchemy model representing a personal trainer's client.
    
    Holds the client's fitness goals, baseline stats, intake history,
    and any recorded joint health or injury considerations.
    """
    __tablename__ = "client_profiles"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    trainer_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("trainers.id", ondelete="CASCADE"), nullable=False, index=True
    )
    full_name: Mapped[str] = mapped_column(String(255), nullable=False)
    email: Mapped[str] = mapped_column(String(255), nullable=True)
    phone: Mapped[str] = mapped_column(String(50), nullable=True)

    # Goals and background
    primary_goal: Mapped[str] = mapped_column(String(255), nullable=True)
    experience_level: Mapped[str] = mapped_column(String(100), nullable=True)
    
    # Structured injury profile used by Agent 2 to flag unsafe load progressions
    # Example JSON: ["Torn left meniscus (2024)", "Chronic lower back stiffness"]
    injuries_json: Mapped[dict] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), default=list, nullable=False
    )
    
    # Raw conversational intake summary generated by Agent 1
    intake_notes: Mapped[str] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=datetime.utcnow, onupdate=datetime.utcnow
    )

    # Relationships
    trainer: Mapped["Trainer"] = relationship("Trainer", back_populates="clients")  # noqa: F821
    sessions: Mapped[list["ClientSession"]] = relationship(
        "ClientSession", back_populates="client", cascade="all, delete-orphan"
    )
    workout_plans: Mapped[list["WorkoutPlan"]] = relationship(  # noqa: F821
        "WorkoutPlan", back_populates="client", cascade="all, delete-orphan"
    )
    workout_logs: Mapped[list["WorkoutLog"]] = relationship(  # noqa: F821
        "WorkoutLog", back_populates="client", cascade="all, delete-orphan"
    )


class ClientSession(Base):
    """
    SQLAlchemy model representing a unique client access session link.
    
    Instead of having clients create email/password accounts, the trainer generates
    a unique URL containing a session token UUID. The client bookmarks this URL on
    their mobile phone for seamless workout logging and progress viewing.
    """
    __tablename__ = "client_sessions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    client_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("client_profiles.id", ondelete="CASCADE"), nullable=False, index=True
    )
    
    # Unique token used in the client mobile URL (/s/:session_token)
    session_token: Mapped[str] = mapped_column(
        String(64),
        unique=True,
        index=True,
        nullable=False,
        default=lambda: str(uuid.uuid4()),
    )
    
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    last_accessed_at: Mapped[datetime] = mapped_column(DateTime, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)

    # Relationship
    client: Mapped["ClientProfile"] = relationship("ClientProfile", back_populates="sessions")
